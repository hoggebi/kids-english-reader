export type FriendCanvasBox = { l: number; t: number; r: number; b: number; hx: number }; // 캔버스(0~1) 기준 친구 그림 영역과 머리 중심

// 미리보기 캔버스(가로:세로 1.2:1)에서 친구 그림이 실제로 차지하는 영역. layout = DecoratedPet이 쓰는 친구 상자.
export function friendCanvasBox(path: string, layout: { x: number; y: number; w: number; h: number }, canvasAspect: number): FriendCanvasBox | null {
  const e = T[path];
  if (!e) return null;
  const [l, t, r, b, hx, a] = e;
  const boxWInW = layout.w; // 캔버스 폭 대비
  const boxHInW = layout.h / canvasAspect; // 캔버스 폭 대비 높이
  const imgW = Math.min(boxWInW, boxHInW * a); // object-contain
  const imgHc = (imgW / a) * canvasAspect; // 캔버스 높이 대비
  const left = layout.x - imgW / 2;
  const top = layout.y - imgHc / 2;
  return { l: left + l * imgW, r: left + r * imgW, t: top + t * imgHc, b: top + b * imgHc, hx: left + hx * imgW };
}
